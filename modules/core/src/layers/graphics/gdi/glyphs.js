/**
 * The glyph rows as bit masks, the leftmost column in the top bit, so a
 * draw tests a bit rather than a character. Built once from the pictures.
 *
 * @type {Map<number, number[]>}
 */
const MASKS = new Map();
for (const [character, rows] of Object.entries(PICTURES))
{
    if (rows.length !== ROWS || rows.some(row=>row.length !== COLUMNS))
    {
        throw new Error(`The glyph for "${character}" is not ${COLUMNS} by ${ROWS}`);
    }
    MASKS.set(character.charCodeAt(0), rows.map(row=>[...row]
        .reduce((mask, dot)=>(mask << 1) | (dot === '#' ? 1 : 0), 0)));
}

/** The rows of a character's glyph as bit masks, or null for one with no picture. */
export const GLYPH_ROWS = ROWS;
export const GLYPH_COLUMNS = COLUMNS;

/**
 * @param {number} code  A character code.
 * @returns {number[] | null}
 */
export function glyphOf(code){
    return MASKS.get(code) ?? null;
}
